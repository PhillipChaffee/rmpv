#!/usr/bin/env python3
"""Regenerates the data tables of the port from mpv's C source.

Usage: tools/gen_tables.py MPV_SOURCE_DIR CRATE_SRC_DIR

Writes codepoint_width_tables.rs and language_tables.rs. The tables are
copied value for value; nothing is computed here.
"""
import re
import sys

mpv, out = sys.argv[1], sys.argv[2]


def wrap(items, per_line):
    lines = []
    for i in range(0, len(items), per_line):
        lines.append("    " + ", ".join(items[i:i + per_line]) + ",")
    return "\n".join(lines)


src = open(f"{mpv}/misc/codepoint_width.c").read()
parts = ["//! Tables of `misc/codepoint_width.c`, generated by `tools/gen_tables.py`.\n"]
for name, ty in (("s_stage0", "u16"), ("s_stage1", "u16"), ("s_stage2", "u16"), ("s_stage3", "u8")):
    body = re.search(r"static const \w+ %s\[\] = \{(.*?)\};" % name, src, re.S).group(1)
    vals = re.findall(r"0x[0-9a-fA-F]+", body)
    parts.append(f"pub(crate) static {name.upper()}: [{ty}; {len(vals)}] = [\n{wrap(vals, 12)}\n];\n")
body = re.search(r"static const uint32_t s_joinRules\[2\]\[16\] = \{(.*?)\};", src, re.S).group(1)
rows = re.findall(r"\{(.*?)\}", body, re.S)
assert len(rows) == 2
parts.append("pub(crate) static S_JOIN_RULES: [[u32; 16]; 2] = [")
for row in rows:
    vals = [v[:6] + "_" + v[6:] for v in re.findall(r"0x[0-9a-fA-F]+", row)]
    assert len(vals) == 16
    parts.append("    [\n" + "\n".join("    " + line for line in wrap(vals, 4).split("\n")) + "\n    ],")
parts.append("];")
open(f"{out}/codepoint_width_tables.rs", "w").write("\n".join(parts) + "\n")

src = open(f"{mpv}/misc/language.c").read()
body = re.search(r"langmap\[\] = \{(.*?)\n\};", src, re.S).group(1)
pairs = re.findall(r"\{L\((\w+)\), L\((\w+)\)\}", body)
assert len(pairs) == body.count("L(") // 2


def field(name, s):
    assert 1 <= len(s) <= 3
    return '%s_s: *b"%s", %s_l: %d' % (name, s.ljust(3, "~").replace("~", "\\0"), name, len(s))


lines = ["//! `langmap` of `misc/language.c`, generated by `tools/gen_tables.py`.\n",
         "use super::Lang;\n",
         "#[rustfmt::skip]",
         f"pub(crate) static LANGMAP: [Lang; {len(pairs)}] = ["]
for m, c in pairs:
    lines.append("    Lang { %s, %s }," % (field("match", m), field("canonical", c)))
lines.append("];")
open(f"{out}/language_tables.rs", "w").write("\n".join(lines) + "\n")
